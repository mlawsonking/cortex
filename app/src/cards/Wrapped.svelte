<script>
  // I9 Monthly Wrapped: the one card on this page that is prose rather than numbers - a monthly brief written by
  // claude -p (Claude Code SUBSCRIPTION, one call per month) over the OTHER engines' contracts.
  //
  // READ-ONLY BY DESIGN - reading pleasure, no verbs. Nothing here acts, and nothing here re-narrates: the text
  // is rendered exactly as the producer stored it. There is deliberately NO deterministic fallback narrative, so
  // if the model ever fails the producer writes nothing and this card ages into a stale badge - which is the
  // honest signal. A hand-written "wrapped" would be the plausible-looking lie the whole app exists to avoid.
  import Card from './Card.svelte';

  let { contract, now } = $props();

  // The producer normalises paragraph breaks to exactly one blank line; split, never reflow or trim content.
  function paragraphs(text) {
    return String(text ?? '').split(/\n{2,}/).map((p) => p.trim()).filter((p) => p.length > 0);
  }
</script>

<Card title="Monthly wrapped" {contract} {now} span={true}>
  {#snippet body(d)}
    <div class="head">
      <span class="chip mono">{d.month}</span>
      <span class="muted">your month in plain language, built only from what the other engines measured</span>
    </div>

    {#each paragraphs(d.narrative) as p, i (i)}
      <p class="para">{p}</p>
    {/each}

    <div class="foot muted">
      generated by claude (subscription, one call per month) &mdash; every figure comes from
      {(d.facts_used ?? []).length} contract{(d.facts_used ?? []).length === 1 ? '' : 's'}:
      <span class="mono">{(d.facts_used ?? []).join(', ')}</span>
    </div>
  {/snippet}
</Card>

